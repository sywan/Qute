#!/usr/bin/env bash
# Qute server setup for Apple Silicon Macs (macOS 13+, 16 GB RAM minimum, 32 GB+ recommended).
#   cd server && ./deploy/mac/setup.sh            # everything (≈25 GB download, 20–40 min)
#   ./deploy/mac/setup.sh --skip-instantid         # without SDXL/InstantID (saves ≈10 GB)
# Re-running is safe: finished steps are skipped.
set -euo pipefail

SERVER="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$SERVER"
SKIP_INSTANTID=0
for arg in "$@"; do
  case "$arg" in
    --skip-instantid) SKIP_INSTANTID=1 ;;
    *) echo "unknown option: $arg"; exit 2 ;;
  esac
done

say() { printf '\n\033[1;35m[qute]\033[0m %s\n' "$*"; }

[ "$(uname -s)" = "Darwin" ] || { echo "This script is for macOS. On Linux + NVIDIA use deploy/linux/docker-compose.yml."; exit 1; }
[ "$(uname -m)" = "arm64" ] || echo "[qute] Warning: not Apple Silicon; the Apple GPU (MPS) will not be available."

say "Checking tools (Xcode Command Line Tools, Homebrew, Python 3.11, CMake, Git)"
xcode-select -p >/dev/null 2>&1 || { echo "Install the Xcode Command Line Tools first: xcode-select --install"; exit 1; }
command -v brew >/dev/null 2>&1 || { echo "Install Homebrew first: https://brew.sh"; exit 1; }
for pkg in python@3.11 cmake git; do brew list "$pkg" >/dev/null 2>&1 || brew install "$pkg"; done
PY311="$(brew --prefix python@3.11)/bin/python3.11"

make_venv() {  # name requirements
  local venv="$SERVER/$1"
  [ -x "$venv/bin/python" ] || "$PY311" -m venv "$venv"
  "$venv/bin/python" -m pip install --quiet --upgrade pip wheel setuptools
  say "Installing $2 into $1 (this can take a while; dlib and insightface compile from source)"
  "$venv/bin/python" -m pip install -r "$2"
}

make_venv .venv-main requirements-gpu.txt
make_venv .venv-dctnet requirements-dctnet.txt
MAIN="$SERVER/.venv-main/bin/python"
DCT="$SERVER/.venv-dctnet/bin/python"

say "Cloning upstream repositories (pinned commits) into server/vendor"
"$MAIN" scripts/vendor.py vtoonify instantid --dest vendor

FAILED=()
step() {  # description command... — keep going if a download fails (pipefail is on), report at the end
  local desc="$1"; shift
  say "$desc"
  if ! "$@" 2>&1 | tee -a logs/setup.log; then FAILED+=("$desc"); fi
}
mkdir -p logs loras

step "Downloading VToonify checkpoints (Hugging Face PKUWilliamYang/VToonify)" \
  "$MAIN" scripts/fetch_models.py vtoonify --vtoonify-dir vendor/VToonify --styles cartoon,comic,arcane,pixar
step "Downloading DCT-Net pipelines (ModelScope; otherwise they download on first use)" \
  "$DCT" scripts/fetch_models.py dctnet
if [ "$SKIP_INSTANTID" = "0" ]; then
  step "Downloading InstantID ControlNet + IP-Adapter" "$MAIN" scripts/fetch_models.py instantid --dest data/instantid
  step "Downloading insightface antelopev2 (~360 MB)" "$MAIN" scripts/fetch_models.py antelopev2 --root data/insightface
  step "Downloading SDXL base, fp16 (~7 GB)" "$MAIN" scripts/fetch_models.py sdxl
  step "Downloading LCM-LoRA" "$MAIN" scripts/fetch_models.py lcm
fi

if [ ! -f .env ]; then
  say "Writing server/.env"
  cat > .env <<EOF
# Qute server settings for this Mac (generated by deploy/mac/setup.sh). Edit and restart run.sh.
QUTE_ALLOWED_ORIGINS=https://sywan.github.io,http://localhost:5173,http://localhost:4173
QUTE_DEVICE=mps
QUTE_MAX_SIDE=1024

# Engines on other processes/machines. dctnet runs from .venv-dctnet via run.sh.
# Add WarpGAN from the Linux GPU box or the Docker worker, e.g. ,warpgan=http://127.0.0.1:8767
QUTE_REMOTE_ENGINES=dctnet=http://127.0.0.1:8766

VTOONIFY_DIR=$SERVER/vendor/VToonify
VTOONIFY_PYTHON=$MAIN
VTOONIFY_DEVICE=cpu

INSTANTID_DIR=$SERVER/vendor/InstantID
INSTANTID_CHECKPOINTS=$SERVER/data/instantid
INSIGHTFACE_ROOT=$SERVER/data/insightface
INSTANTID_BASE_MODEL=stabilityai/stable-diffusion-xl-base-1.0
INSTANTID_LCM=1
INSTANTID_STEPS=8
INSTANTID_SIZE=768x1024
# Put your SDXL chibi LoRA here:
CHIBI_LORA=$SERVER/loras/chibi.safetensors
CHIBI_LORA_SCALE=0.9
EOF
fi

if [ "${#FAILED[@]}" -gt 0 ]; then
  say "Setup finished with ${#FAILED[@]} failed step(s); see server/logs/setup.log:"
  printf '   - %s\n' "${FAILED[@]}"
  echo "   Re-run ./deploy/mac/setup.sh to retry (finished downloads are skipped)."
else
  say "Setup complete."
fi
say "Put your chibi LoRA at server/loras/chibi.safetensors, then start:  ./deploy/mac/run.sh  → open http://localhost:8765"
